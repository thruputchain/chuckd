package kernel

import (
	proto "github.com/groundhogchain/protocol-go"
)

type BallotProtocol struct {
	slot            proto.SCPSlotIndex
	heardFromQuorum bool

	currentBallot   *proto.SCPBallot // b
	prepared        *proto.SCPBallot // p
	preparedPrime   *proto.SCPBallot // p'
	highBallot      *proto.SCPBallot // h
	commit          *proto.SCPBallot // c
	latestEnvelopes map[proto.SCPNodeID]*proto.SCPEnvelope
	phase           SCPPhase        // Phi
	valueOverride   *proto.SCPValue // z

	currentMessageLevel int // number of messages triggered in one run

	// The number of times the timer has expired.
	// This is used for the quorum endpoint.
	timerExpCount int32

	lastEnvelope      *proto.SCPEnvelope // last envelope generated by this node
	mLastEnvelopeEmit *proto.SCPEnvelope // last envelope emitted by this node
}

type SCPPhase int

const (
	SCPPhasePrepare SCPPhase = iota
	SCPPhaseConfirm
	SCPPhaseExternalize
	SCPPhaseNum
)

func (x SCPPhase) String() string {
	switch x {
	case SCPPhasePrepare:
		return "Prepare"
	case SCPPhaseConfirm:
		return "Confirm"
	case SCPPhaseExternalize:
		return "Externalize"
	case SCPPhaseNum:
		return "Num"
	}
	panic("unreachable")
}

func NewBallotProtocol(slot proto.SCPSlotIndex) *BallotProtocol {
	return &BallotProtocol{
		slot:                slot,
		heardFromQuorum:     false,
		phase:               SCPPhasePrepare,
		currentMessageLevel: 0,
		timerExpCount:       0,
	}
}
