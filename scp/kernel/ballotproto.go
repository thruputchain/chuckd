type BallotProtocol struct {
	ctx             context.Context // XXX: must set on init
	slot            *Slot
	heardFromQuorum bool

	currentBallot   *proto.SCPBallot // b
	prepared        *proto.SCPBallot // p
	preparedPrime   *proto.SCPBallot // p'
	highBallot      *proto.SCPBallot // h
	commit          *proto.SCPBallot // c
	latestEnvelopes map[proto.SCPNodeID]*proto.SCPEnvelope
	phase           SCPPhase       // Phi
	valueOverride   proto.SCPValue // z

	currentMessageLevel int // number of messages triggered in one run

	// The number of times the timer has expired.
	// This is used for the quorum endpoint.
	timerExpCount int32

	lastEnvelope     *proto.SCPEnvelope // last envelope generated by this node
	lastEnvelopeEmit *proto.SCPEnvelope // last envelope emitted by this node
}

type SCPPhase int

const (
	SCPPhasePrepare SCPPhase = iota
	SCPPhaseConfirm
	SCPPhaseExternalize
	SCPPhaseNum
)

func (x SCPPhase) String() string {
	switch x {
	case SCPPhasePrepare:
		return "Prepare"
	case SCPPhaseConfirm:
		return "Confirm"
	case SCPPhaseExternalize:
		return "Externalize"
	case SCPPhaseNum:
		return "Num"
	}
	panic("unreachable")
}

func NewBallotProtocol(slot *Slot) *BallotProtocol {
	return &BallotProtocol{
		slot:                slot,
		heardFromQuorum:     false,
		phase:               SCPPhasePrepare,
		currentMessageLevel: 0,
		timerExpCount:       0,
	}
}

func (x *BallotProtocol) isNewerStatement(nodeID proto.SCPNodeID, st *proto.SCPStatement) bool {
	oldp, ok := x.latestEnvelopes[nodeID]
	if !ok {
		return true
	}
	return isNewerStatement(&oldp.Statement, st)
}

func isNewerStatement(oldst *proto.SCPStatement, st *proto.SCPStatement) bool {

	// total ordering described in SCP paper.
	t := st.Pledges.Type

	// statement type (PREPARE < CONFIRM < EXTERNALIZE)
	if oldst.Pledges.Type != t {
		return oldst.Pledges.Type < t
	}

	// can't have duplicate EXTERNALIZE statements
	switch t {

	case proto.SCP_ST_EXTERNALIZE:
		return false

	case proto.SCP_ST_CONFIRM:

		// sorted by (b, p, p', h) (p' = 0 implicitly)
		oldC := oldst.Pledges.Confirm()
		c := st.Pledges.Confirm()

		compBallot := compareBallots(oldC.Ballot, c.Ballot)
		if compBallot < 0 {
			return true
		} else if compBallot == 0 {
			if oldC.NPrepared == c.NPrepared {
				return oldC.NH < c.NH
			} else {
				return oldC.NPrepared < c.NPrepared
			}
		}

	default:

		// Lexicographical order between PREPARE statements:
		// (b, p, p', h)
		oldPrep := oldst.Pledges.Prepare()
		prep := st.Pledges.Prepare()

		compBallot := compareBallots(oldPrep.Ballot, prep.Ballot)
		if compBallot < 0 {
			return true
		} else if compBallot == 0 {
			compBallot = compareBallotPtrs(oldPrep.Prepared, prep.Prepared)
			if compBallot < 0 {
				return true
			} else if compBallot == 0 {
				compBallot = compareBallotPtrs(oldPrep.PreparedPrime, prep.PreparedPrime)
				if compBallot < 0 {
					return true
				} else if compBallot == 0 {
					return oldPrep.NH < prep.NH
				}
			}
		}

	}
	panic("unreachable")
}

func compareBallots(b1 proto.SCPBallot, b2 proto.SCPBallot) int {

	if b1.Counter < b2.Counter {
		return -1
	} else if b2.Counter < b1.Counter {
		return 1
	}

	// ballots are also strictly ordered by value
	return bytes.Compare(b1.Value, b2.Value)
}

func compareBallotPtrs(b1 *proto.SCPBallot, b2 *proto.SCPBallot) int {
	switch {
	case b1 != nil && b2 != nil:
		return compareBallots(*b1, *b2)
	case b1 != nil && b2 == nil:
		return 1
	case b1 == nil && b2 != nil:
		return -1
	default:
		return 0
	}
}

func (x *BallotProtocol) recordEnvelope(env *proto.SCPEnvelope) {
	nodeID := env.Statement.NodeID
	x.latestEnvelopes[nodeID] = env
	x.slot.recordStatement(&env.Statement)
}

func (x *BallotProtocol) processEnvelope(ctx context.Context, env *proto.SCPEnvelope, self bool) EnvelopeState {
	must.Assertf(ctx, env.Statement.SlotIndex == x.slot.getSlotIndex(), "env/slot mismatch")

	statement := &env.Statement
	nodeID := statement.NodeID

	if !x.isSaneStatement(ctx, statement, self) {
		if self {
			liblog.Errorf("not sane statement from self, skipping %v", form.Display(env))
		}
		return EnvelopeStateInvalid
	}

	if !x.isNewerStatement(nodeID, statement) {
		if self {
			liblog.Errorf("stale statement from self, skipping %v", form.Display(env))
		} else {
			liblog.Tracef("stale statement, skipping %d", x.slot.getSlotIndex())
		}
		return EnvelopeStateInvalid
	}

	validationRes := x.validateValues(ctx, statement)

	if validationRes == InvalidValue {
		if self {
			liblog.Errorf("invalid value from self, skipping %v", form.Display(env))
		} else {
			liblog.Tracef("invalid value %d", x.slot.getSlotIndex())
		}
		return EnvelopeStateInvalid
	}

	if x.phase != SCPPhaseExternalize {
		if validationRes == MaybeValidValue {
			x.slot.setFullyValidated(false)
		}
		x.recordEnvelope(env)
		x.advanceSlot(statement)
		return EnvelopeStateValid
	}

	// note: this handles also our own messages
	// in particular our final EXTERNALIZE message
	must.Assertf(ctx, x.phase == SCPPhaseExternalize, "expecting externalize phase")
	if bytes.Compare(x.commit.Value, x.getWorkingBallot(statement).Value) == 0 {
		x.recordEnvelope(env)
		return EnvelopeStateValid
	}

	if self {
		liblog.Errorf("externalize statement with invalid value from self, skipping %v", form.Display(env))
	}

	return EnvelopeStateInvalid
}

func (x *BallotProtocol) isSaneStatement(ctx context.Context, stmt *proto.SCPStatement, self bool) bool {

	qSet := x.slot.getQuorumSetFromStatement(stmt)
	if qSet == nil {
		liblog.Debugf("unrecognized quorum set received")
		return false
	}
	if err := isQuorumSetSane(qSet, false); err != nil {
		liblog.Debugf("invalid quorum set received: %v", err)
		return false
	}

	switch stmt.Pledges.Type {
	case proto.SCP_ST_PREPARE:

		p := stmt.Pledges.Prepare()

		// self is allowed to have b = 0 (as long as it never gets emitted)
		ok := self || p.Ballot.Counter > 0

		ok = ok &&
			((p.PreparedPrime == nil || p.Prepared == nil) ||
				(x.areBallotsLessAndIncompatible(*p.PreparedPrime, *p.Prepared)))

		ok = ok && (p.NH == 0 || (p.Prepared != nil && p.NH <= p.Prepared.Counter))

		// c != 0 -> c <= h <= b
		ok = ok && (p.NC == 0 || (p.NH != 0 && p.Ballot.Counter >= p.NH && p.NH >= p.NC))

		if !ok {
			liblog.Tracef("malformed PREPARE message")
		}
		return ok

	case proto.SCP_ST_CONFIRM:

		c := stmt.Pledges.Confirm()

		// c <= h <= b
		ok := c.Ballot.Counter > 0 && c.NH <= c.Ballot.Counter && c.NCommit <= c.NH
		if !ok {
			liblog.Tracef("malformed CONFIRM message")
		}
		return ok

	case proto.SCP_ST_EXTERNALIZE:

		e := stmt.Pledges.Externalize()

		ok := e.Commit.Counter > 0 && e.NH >= e.Commit.Counter
		if !ok {
			liblog.Tracef("malformed EXTERNALIZE message")
		}
		return ok

	default:
		panic("abort")
	}
}

func (x *BallotProtocol) abandonBallot(ctx context.Context, n proto.SCPCount) bool {

	liblog.Tracef("abandoning ballot")

	v := x.slot.getLatestCompositeCandidate()

	if len(v) == 0 {
		if x.currentBallot != nil {
			v = x.currentBallot.Value
		}
	}

	if len(v) > 0 {
		if n == 0 {
			return x.bumpState(ctx, v, true)
		} else {
			return x.bumpStateN(ctx, v, n)
		}
	}

	return false
}

func (x *BallotProtocol) bumpState(ctx context.Context, value proto.SCPValue, force bool) bool {

	if !force && x.currentBallot != nil {
		return false
	}

	var n proto.SCPCount
	if x.currentBallot != nil {
		n = x.currentBallot.Counter + 1
	} else {
		n = 1
	}
	return x.bumpStateN(ctx, value, n)
}

func (x *BallotProtocol) bumpStateN(ctx context.Context, value proto.SCPValue, n proto.SCPCount) bool {

	if x.phase != SCPPhasePrepare && x.phase != SCPPhaseConfirm {
		return false
	}

	var newb proto.SCPBallot

	newb.Counter = n

	if x.valueOverride != nil {
		// we use the value that we saw confirmed prepared
		// or that we at least voted to commit to
		newb.Value = x.valueOverride
	} else {
		newb.Value = value
	}

	liblog.Tracef("bump state i=%d v=%v",
		x.slot.getSlotIndex(), form.Display(newb))

	updated := x.updateCurrentValue(ctx, newb)

	if updated {
		x.emitCurrentStateStatement()
		x.checkHeardFromQuorum()
	}

	return updated
}

// updates the local state based to the specified ballot
// (that could be a prepared ballot) enforcing invariants
func (x *BallotProtocol) updateCurrentValue(ctx context.Context, ballot proto.SCPBallot) bool {

	if x.phase != SCPPhasePrepare && x.phase != SCPPhaseConfirm {
		return false
	}

	var updated bool
	if x.currentBallot == nil {
		x.bumpToBallot(ctx, ballot, true)
		updated = true
	} else {
		must.Assert(ctx, compareBallots(*x.currentBallot, ballot) <= 0)

		if x.commit != nil && !x.areBallotsCompatible(*x.commit, ballot) {
			return false
		}

		if q := compareBallots(*x.currentBallot, ballot); q < 0 {
			x.bumpToBallot(ctx, ballot, true)
			updated = true
		} else if q > 0 {
			// this code probably changes with the final version
			// of the conciliator

			// this case may happen if the other nodes are not
			// following the protocol (and we end up with a smaller value)
			// not sure what is the best way to deal
			// with this situation
			liblog.Errorf("attempt to bump to a smaller value")
			// can't just bump to the value as we may already have
			// statements at counter+1
			return false
		}
	}

	x.checkInvariants()

	return updated
}

func (x *BallotProtocol) bumpToBallot(ctx context.Context, ballot proto.SCPBallot, check bool) {

	liblog.Tracef("bump to ballot i=%d v=%v", x.slot.getSlotIndex(), form.Display(ballot))

	must.Assert(ctx, x.phase != SCPPhaseExternalize)

	if check {
		// We should move mCurrentBallot monotonically only
		must.Assert(ctx, x.currentBallot == nil ||
			compareBallots(ballot, *x.currentBallot) >= 0)
	}

	gotBumped := x.currentBallot == nil || x.currentBallot.Counter != ballot.Counter

	if x.currentBallot == nil {
		x.slot.Driver().StartedBallotProtocol(x.slot.getSlotIndex(), ballot)
	}

	x.currentBallot = &ballot

	// note: we have to clear some fields (and recompute them based on latest
	// messages)
	// invariant: h.value = b.value
	if x.highBallot != nil && !x.areBallotsCompatible(*x.currentBallot, *x.highBallot) {
		x.highBallot = nil
		// invariant: c set only when h is set
		x.commit = nil
	}

	if gotBumped {
		x.heardFromQuorum = false
	}
}

func (x *BallotProtocol) startBallotProtocolTimer() {
	timeout := x.slot.Driver().ComputeTimeout(x.currentBallot.Counter)
	x.slot.Driver().StartTimer(
		x.slot.getSlotIndex(),
		BallotProtocolTimer,
		timeout,
		x.ballotProtocolTimerExpired,
	)
}

func (x *BallotProtocol) stopBallotProtocolTimer() {
	x.slot.Driver().StopTimer(
		x.slot.getSlotIndex(),
		BallotProtocolTimer,
	)
}

func (x *BallotProtocol) ballotProtocolTimerExpired() {
	x.timerExpCount += 1
	x.abandonBallot(x.ctx, 0)
}

