type BallotProtocol struct {
	slot            *Slot
	heardFromQuorum bool

	currentBallot   *proto.SCPBallot // b
	prepared        *proto.SCPBallot // p
	preparedPrime   *proto.SCPBallot // p'
	highBallot      *proto.SCPBallot // h
	commit          *proto.SCPBallot // c
	latestEnvelopes map[proto.SCPNodeID]*proto.SCPEnvelope
	phase           SCPPhase        // Phi
	valueOverride   *proto.SCPValue // z

	currentMessageLevel int // number of messages triggered in one run

	// The number of times the timer has expired.
	// This is used for the quorum endpoint.
	timerExpCount int32

	lastEnvelope     *proto.SCPEnvelope // last envelope generated by this node
	lastEnvelopeEmit *proto.SCPEnvelope // last envelope emitted by this node
}

type SCPPhase int

const (
	SCPPhasePrepare SCPPhase = iota
	SCPPhaseConfirm
	SCPPhaseExternalize
	SCPPhaseNum
)

func (x SCPPhase) String() string {
	switch x {
	case SCPPhasePrepare:
		return "Prepare"
	case SCPPhaseConfirm:
		return "Confirm"
	case SCPPhaseExternalize:
		return "Externalize"
	case SCPPhaseNum:
		return "Num"
	}
	panic("unreachable")
}

func NewBallotProtocol(slot *Slot) *BallotProtocol {
	return &BallotProtocol{
		slot:                slot,
		heardFromQuorum:     false,
		phase:               SCPPhasePrepare,
		currentMessageLevel: 0,
		timerExpCount:       0,
	}
}

func (x *BallotProtocol) isNewerStatement(nodeID proto.SCPNodeID, st *proto.SCPStatement) bool {
	oldp, ok := x.latestEnvelopes[nodeID]
	if !ok {
		return true
	}
	return isNewerStatement(&oldp.Statement, st)
}

func isNewerStatement(oldst *proto.SCPStatement, st *proto.SCPStatement) bool {

	// total ordering described in SCP paper.
	t := st.Pledges.Type

	// statement type (PREPARE < CONFIRM < EXTERNALIZE)
	if oldst.Pledges.Type != t {
		return oldst.Pledges.Type < t
	}

	// can't have duplicate EXTERNALIZE statements
	switch t {

	case proto.SCP_ST_EXTERNALIZE:
		return false

	case proto.SCP_ST_CONFIRM:

		// sorted by (b, p, p', h) (p' = 0 implicitly)
		oldC := oldst.Pledges.Confirm()
		c := st.Pledges.Confirm()

		compBallot := compareBallots(oldC.Ballot, c.Ballot)
		if compBallot < 0 {
			return true
		} else if compBallot == 0 {
			if oldC.NPrepared == c.NPrepared {
				return oldC.NH < c.NH
			} else {
				return oldC.NPrepared < c.NPrepared
			}
		}

	default:

		// Lexicographical order between PREPARE statements:
		// (b, p, p', h)
		oldPrep := oldst.Pledges.Prepare()
		prep := st.Pledges.Prepare()

		compBallot := compareBallots(oldPrep.Ballot, prep.Ballot)
		if compBallot < 0 {
			return true
		} else if compBallot == 0 {
			compBallot = compareBallotPtrs(oldPrep.Prepared, prep.Prepared)
			if compBallot < 0 {
				return true
			} else if compBallot == 0 {
				compBallot = compareBallotPtrs(oldPrep.PreparedPrime, prep.PreparedPrime)
				if compBallot < 0 {
					return true
				} else if compBallot == 0 {
					return oldPrep.NH < prep.NH
				}
			}
		}

	}
	panic("unreachable")
}

func compareBallots(b1 proto.SCPBallot, b2 proto.SCPBallot) int {

	if b1.Counter < b2.Counter {
		return -1
	} else if b2.Counter < b1.Counter {
		return 1
	}

	// ballots are also strictly ordered by value
	return bytes.Compare(b1.Value, b2.Value)
}

func compareBallotPtrs(b1 *proto.SCPBallot, b2 *proto.SCPBallot) int {
	switch {
	case b1 != nil && b2 != nil:
		return compareBallots(*b1, *b2)
	case b1 != nil && b2 == nil:
		return 1
	case b1 == nil && b2 != nil:
		return -1
	default:
		return 0
	}
}

func (x *BallotProtocol) recordEnvelope(env *proto.SCPEnvelope) {
	nodeID := env.Statement.NodeID
	x.latestEnvelopes[nodeID] = env
	x.slot.recordStatement(&env.Statement)
}

func (x *BallotProtocol) processEnvelope(ctx context.Context, env *proto.SCPEnvelope, self bool) EnvelopeState {
	must.Assertf(ctx, env.Statement.SlotIndex == x.slot.getSlotIndex(), "env/slot mismatch")

	statement := &env.Statement
	nodeID := statement.NodeID

	if !x.isSaneStatement(ctx, statement, self) {
		if self {
			liblog.Errorf("not sane statement from self, skipping %v", form.Display(env))
		}
		return EnvelopeStateInvalid
	}

	if !x.isNewerStatement(nodeID, statement) {
		if self {
			liblog.Errorf("stale statement from self, skipping %v", form.Display(env))
		} else {
			liblog.Tracef("stale statement, skipping %d", x.slot.getSlotIndex())
		}
		return EnvelopeStateInvalid
	}

	panic("XXX")
}

