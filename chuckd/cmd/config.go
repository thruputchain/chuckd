package cmd

import (
	cryptorand "crypto/rand"
	"errors"
	"fmt"
	"math/rand"
	"os"
	"strings"
	"time"

	"github.com/groundhogchain/chuckd/chuckd/cmdkit"
	"github.com/groundhogchain/chuckd/deploy/common"
	"github.com/groundhogchain/chuckd/util/protoutil"
	"github.com/groundhogchain/lib-go/libtext"
	"github.com/groundhogchain/lib-go/must"
	proto "github.com/groundhogchain/protocol-go"
	"github.com/spf13/cobra"
)

var (
	configCmd = &cobra.Command{
		Use:   "config",
		Short: "tools to manipulate validator configuration",
		Long:  ``,
		Run:   func(cmd *cobra.Command, args []string) {},
	}

	configInitCmd = &cobra.Command{
		Use:   "init",
		Short: "initialize identity and create barebones config",
		Long:  ``,
		RunE: func(cmd *cobra.Command, args []string) error {
			return cmdkit.Invoke(ctx, func() {
				vcfg := protoutil.InitConfig(ctx, cryptorand.Reader, "")
				cfg := proto.Config{
					Validator_config: vcfg,
				}
				if configToStdout {
					fmt.Println(libtext.Display(cfg))
				} else {
					cfgPath := effectiveConfigPath(ctx)
					_, err := os.Stat(cfgPath)
					if errors.Is(err, os.ErrNotExist) {
						err := os.WriteFile(cfgPath, libtext.SprintJSONBytes(cfg), 0644)
						must.NoError(ctx, err)
					} else {
						must.NoError(ctx, err)
						must.Errorf(ctx, "config already exists: %s", cfgPath)
					}
				}
			})
		},
	}

	configGroupCmd = &cobra.Command{
		Use:   "group",
		Short: "generate a group of configs",
		Long:  ``,
		RunE: func(cmd *cobra.Command, args []string) error {
			return cmdkit.Invoke(ctx, func() {
				vcfgs := protoutil.GenerateConfigs(ctx, cryptorand.Reader, configGroupSize)
				cfgs := make([]*proto.Config, len(vcfgs))
				for i := range vcfgs {
					cfgs[i] = &proto.Config{
						Validator_config: vcfgs[i],
					}
				}
				protoutil.WriteConfigsToDir(ctx, cfgs, configOutputDir)
			})
		},
	}

	configQuorumCmd = &cobra.Command{
		Use:   "quorum",
		Short: "generate a full config per validator in a quorum",
		Long: `Writes one complete config per validator: the identities and quorum set
of [config group], plus the SCP, discovery, router, dogwood, mempool,
catchup, baton, repair and storage sections a coordinator needs to run.

Identities come from --seed, so the same seed and addresses always produce
the same configs. Checked-in configs are regenerated by rerunning the
command that produced them, which keeps them in step with the protocol
rather than hand-edited after it changes.`,
		RunE: func(cmd *cobra.Command, args []string) error {
			return cmdkit.Invoke(ctx, func() {
				addrs := strings.Split(configQuorumAddrs, ",")
				for i, addr := range addrs {
					addrs[i] = strings.TrimSpace(addr)
					must.Assertf(ctx, addrs[i] != "",
						"--addresses entry %d is empty", i)
				}
				round := time.Duration(configQuorumRoundMsec) * time.Millisecond
				base := common.MakeBaseConfig(
					round, int64(len(addrs)), uint32(configQuorumFanOut))
				cfgs, _ := common.GenQuorumConfigs(
					ctx,
					rand.New(rand.NewSource(configQuorumSeed)),
					base,
					addrs,
				)
				out := make([]*proto.Config, len(cfgs))
				for i := range cfgs {
					out[i] = &cfgs[i]
				}
				protoutil.WriteConfigsToDir(ctx, out, configOutputDir)
			})
		},
	}
)

var (
	configToStdout        bool
	configGroupSize       int
	configOutputDir       string
	configQuorumAddrs     string
	configQuorumSeed      int64
	configQuorumRoundMsec int
	configQuorumFanOut    int
)

func init() {
	rootCmd.AddCommand(configCmd)

	configCmd.AddCommand(configInitCmd)
	configInitCmd.Flags().BoolVar(&configToStdout, "stdout", false, "output to stdout")

	configCmd.AddCommand(configGroupCmd)
	configGroupCmd.Flags().IntVar(&configGroupSize, "size", 3, "size of group")
	configGroupCmd.Flags().StringVar(&configOutputDir, "outdir", ".", "output directory")

	configCmd.AddCommand(configQuorumCmd)
	configQuorumCmd.Flags().StringVar(&configQuorumAddrs, "addresses", "",
		"comma-separated validator addresses, one per config")
	configQuorumCmd.Flags().Int64Var(&configQuorumSeed, "seed", 1,
		"seed for validator identity generation")
	configQuorumCmd.Flags().IntVar(&configQuorumRoundMsec, "round-msec", 1000,
		"target round duration, msec")
	configQuorumCmd.Flags().IntVar(&configQuorumFanOut, "fan-out", 5, "tree fan out")
	configQuorumCmd.Flags().StringVar(&configOutputDir, "outdir", ".", "output directory")
	must.NoError(ctx, configQuorumCmd.MarkFlagRequired("addresses"))
}
