package protoutil

import (
	"encoding/hex"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"testing"

	proto "github.com/groundhogchain/protocol-go"
)

const rustSignInteropEnvVar = "RUN_CHUCKD_RUST_INTEROP_TEST"

func TestVerifyBytesAcceptsRustSignBytes(t *testing.T) {
	if os.Getenv(rustSignInteropEnvVar) != "1" {
		t.Skipf("set %s=1 to run this integration test", rustSignInteropEnvVar)
	}
	if testing.Short() {
		t.Skip("skipping rust interop integration test in short mode")
	}
	if _, err := exec.LookPath("cargo"); err != nil {
		t.Skip("skipping rust interop integration test: cargo not found")
	}

	message := []byte("cross-language VerifyBytes compatibility check")
	fixture := rustSignFixture(t, "verify-bytes-interop-seed", message)

	publicKey := proto.ValidatorPublicKey{Scheme: proto.Ed25519}
	if len(fixture.publicKey) != len(*publicKey.Ed25519()) {
		t.Fatalf("unexpected public key size: got %d want %d", len(fixture.publicKey), len(*publicKey.Ed25519()))
	}
	copy(publicKey.Ed25519()[:], fixture.publicKey)

	if !VerifyBytes(publicKey, message, fixture.signature) {
		t.Fatal("VerifyBytes rejected a signature generated by rust scp_util sign_bytes")
	}
}

type rustFixture struct {
	publicKey []byte
	signature []byte
}

func rustSignFixture(t *testing.T, seed string, msg []byte) rustFixture {
	t.Helper()

	manifestPath := rustManifestPath(t)
	msgHex := hex.EncodeToString(msg)

	cmd := exec.Command(
		"cargo",
		"run",
		"--quiet",
		"--manifest-path",
		manifestPath,
		"-p",
		"scp_util",
		"--bin",
		"sign_bytes_fixture",
		"--",
		seed,
		msgHex,
	)
	cmd.Dir = filepath.Dir(filepath.Dir(manifestPath))

	output, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("cargo run sign_bytes_fixture failed: %v\n%s", err, string(output))
	}

	return rustFixture{
		publicKey: parseHexLine(t, output, "PUBLIC_KEY_HEX="),
		signature: parseHexLine(t, output, "SIGNATURE_HEX="),
	}
}

func rustManifestPath(t *testing.T) string {
	t.Helper()

	_, filename, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("failed to locate current test file path")
	}

	chuckdRoot := filepath.Clean(filepath.Join(filepath.Dir(filename), "..", ".."))
	manifestPath := filepath.Join(chuckdRoot, "scp", "Cargo.toml")
	if _, err := os.Stat(manifestPath); err != nil {
		t.Fatalf("could not find rust cargo manifest at %s: %v", manifestPath, err)
	}
	return manifestPath
}

func parseHexLine(t *testing.T, output []byte, prefix string) []byte {
	t.Helper()

	for _, line := range strings.Split(string(output), "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, prefix) {
			continue
		}

		value := strings.TrimPrefix(line, prefix)
		decoded, err := hex.DecodeString(value)
		if err != nil {
			t.Fatalf("failed to decode %s value %q: %v", prefix, value, err)
		}
		return decoded
	}

	t.Fatalf("missing %s line in output:\n%s", prefix, string(output))
	return nil
}
